#!/usr/bin/env bash
# 00-prereqs.sh
# Asterward Lumen Sync, Phase 0.
# One-time setup: write config, install icloudpd/exiftool/fdupes, create the folder structure.
# Idempotent, safe to re-run.

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

echo "[$(ts)] Phase 0: prerequisites"

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
if [[ ! -f "$CONFIG_FILE" ]]; then
    echo "[$(ts)] No config found. Creating $CONFIG_FILE"
    mkdir -p "$(dirname "$CONFIG_FILE")"

    read -r -p "Apple ID email: " _apple_id
    [[ -n "$_apple_id" ]] || { echo "ERROR: Apple ID is required."; exit 1; }
    read -r -p "Creator name for copyright metadata [$CREATOR]: " _creator
    _creator="${_creator:-$CREATOR}"
    read -r -p "Rights / portfolio URL (blank to omit): " _rights_url
    read -r -p "Target root [$TARGET_ROOT]: " _target
    _target="${_target:-$TARGET_ROOT}"

    umask 077
    # printf %q escapes quotes and $ so names like O'Brien cannot break the file.
    {
        echo "# Generated by 00-prereqs.sh on $(ts)"
        echo "# Holds no password. icloudpd prompts for the password and 2FA code interactively."
        printf 'APPLE_ID=%q\n' "$_apple_id"
        printf 'TARGET_ROOT=%q\n' "$_target"
        printf 'CREATOR=%q\n' "$_creator"
        printf 'CREATOR_LOCATION=%q\n' "$CREATOR_LOCATION"
        printf 'CREATOR_COUNTRY_CODE=%q\n' "$CREATOR_COUNTRY_CODE"
        printf 'RIGHTS_URL=%q\n' "$_rights_url"
        echo "KEEP_LIVE_PHOTO_MOVS=1"
        echo "EMBED_METADATA=0"
        echo "ADP_WEB_ACCESS=0"
        echo "MIN_FREE_GB=${MIN_FREE_GB:-1100}"
    } > "$CONFIG_FILE"
    chmod 600 "$CONFIG_FILE"
    # shellcheck disable=SC1090
    source "$CONFIG_FILE"
    echo "[$(ts)] Config written to $CONFIG_FILE"
else
    echo "[$(ts)] Using existing config at $CONFIG_FILE"
fi

: "${APPLE_ID:?ERROR: APPLE_ID missing from $CONFIG_FILE}"

# ---------------------------------------------------------------------------
# Target drive
# ---------------------------------------------------------------------------
require_mount
echo "[$(ts)] Creating folder structure at $TARGET_ROOT"
mkdir -p "$TARGET_ROOT"/{originals,logs,manifests,quarantine/duplicates,quarantine/junk,.icloudpd-cache}

# shellcheck disable=SC2034  # read by log() in common.sh
LOG_FILE="$TARGET_ROOT/logs/00-prereqs-$(date -u +%Y%m%dT%H%M%SZ).log"
log "Phase 0 started"

FS_TYPE="$(detect_fs)"
log "Filesystem: ${FS_TYPE:-unknown}"
if [[ "$FS_TYPE" == "exfat" || "$FS_TYPE" == "msdos" ]]; then
    log "exFAT detected. Deliberate operator choice for Windows interoperability."
    log "Compensations active: junk/AppleDouble exclusion in every scan, case-insensitive"
    log "sidecar matching, no hardlink or POSIX permission assumptions."
    log "NOTE: keep the Lightroom catalog off this volume. SQLite on exFAT risks corruption."
fi

# 1.1 TB suits the full ~850 GB library. Lower MIN_FREE_GB for a sample run.
check_free_space "${MIN_FREE_GB:-1100}"

# ---------------------------------------------------------------------------
# Tooling
# ---------------------------------------------------------------------------
if ! command -v pipx >/dev/null 2>&1; then
    log "Installing pipx"
    brew install pipx
    pipx ensurepath
fi
# Append, never prepend: whatever is already first on PATH keeps priority.
export PATH="$PATH:$HOME/.local/bin"

# Pin icloudpd. Its flags and its existing-file matching change between
# releases, and an unpinned --force reinstall can change behaviour mid-migration.
_have_ipd="$(icloudpd --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n1 || true)"
if [[ "$_have_ipd" != "$ICLOUDPD_VERSION" ]]; then
    log "Installing icloudpd $ICLOUDPD_VERSION (found: ${_have_ipd:-none})"
    pipx install --force "icloudpd==$ICLOUDPD_VERSION"
else
    log "icloudpd $ICLOUDPD_VERSION already installed"
fi

for tool in exiftool fdupes; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        log "Installing $tool"
        brew install "$tool"
    fi
done

# ---------------------------------------------------------------------------
# Verify
# ---------------------------------------------------------------------------
log "icloudpd $(icloudpd --version 2>&1 | head -n1)"
log "exiftool $(exiftool -ver)"
log "fdupes $(fdupes --version 2>&1 | head -n1)"

# icloudpd's CLI surface changes between releases, so record what this build
# actually accepts instead of assuming the flags hardcoded in 01-extract.sh.
# Always refresh, so a version change is picked up by the later phases.
icloudpd --help > "$TARGET_ROOT/manifests/00-icloudpd-help.txt" 2>&1 || true
log "icloudpd option list saved to manifests/00-icloudpd-help.txt"

log "Phase 0 complete"
echo
echo "Run these yourself, they need sudo and this script will not escalate:"
echo "  sudo pmset -a disksleep 0                 # stop the HDD sleeping mid-transfer"
echo "  sudo mdutil -i off \"\$(dirname \"\$TARGET_ROOT\")\"  # optional, stops Spotlight thrashing the HDD"
